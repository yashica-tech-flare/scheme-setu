// Fallback resolver: returns native language dict if defined, else Hindi for Indic, else English
function getTranslation(lang, key) {
  if (DICT[lang] && DICT[lang][key]) return DICT[lang][key];
  // Dialects of Hindi / northern Indic default to Hindi
  const hindiDialects = ['bgc', 'bho', 'hne', 'mag', 'mai', 'raj', 'doi', 'ks', 'ne', 'sa', 'kok', 'gon', 'kha', 'lus', 'mni', 'brx', 'sat', 'sd', 'tcy'];
  if (hindiDialects.includes(lang) && DICT.hi[key]) return DICT.hi[key];
  return DICT.en[key] || '';
}

