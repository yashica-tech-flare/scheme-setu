// Check valid MP3 header
function isValidMp3(buf) {
  if (!buf || buf.length < 2048) return false;
  const hasId3 = buf[0] === 0x49 && buf[1] === 0x44 && buf[2] === 0x33;
  const hasSync = buf[0] === 0xff && (buf[1] & 0xe0) === 0xe0;
  return hasId3 || hasSync;
}

// Sarvam API caller
function synthesizeSarvam(text, targetLang) {
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify({
      text: text,
      language_code: targetLang,
      speaker: 'shubh',
      model: 'bulbul:v3',
      output_audio_codec: 'mp3'
    });

    const req = https.request({
      hostname: 'api.sarvam.ai',
      path: '/text-to-speech',
      method: 'POST',
      headers: {
        'api-subscription-key': SARVAM_KEY,
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(payload)
      },
      timeout: 30000
    }, (res) => {
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          try {
            const parsed = JSON.parse(body);
            if (parsed.audios && parsed.audios[0]) {
              const audioBuf = Buffer.from(parsed.audios[0], 'base64');
              return resolve(audioBuf);
            }
            reject(new Error('Sarvam response missing audios array'));
          } catch (e) {
            reject(new Error(`Failed parsing Sarvam JSON: ${e.message}`));
          }
        } else {
          reject(new Error(`Sarvam API returned HTTP ${res.statusCode}: ${body.slice(0, 200)}`));
        }
      });
    });

    req.on('timeout', () => {
      req.destroy();
      reject(new Error('Sarvam request timed out'));
    });
    req.on('error', err => reject(err));
    req.write(payload);
    req.end();
  });
}

function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function run() {
  console.log('===============================================================');
  console.log('       SchemeBridge Static Voice Pre-Generation (Part 2B)      ');
  console.log('===============================================================\n');

  // Verify frozen baseline
  console.log('Auditing frozen baseline hashes...');
  for (const [key, clip] of Object.entries(baseline.clips)) {
    const fullPath = path.resolve(__dirname, '../frontend/public' + clip.path);
    if (!fs.existsSync(fullPath)) {
      console.error(`FATAL: Frozen baseline clip missing on disk: ${clip.path}`);
      process.exit(1);
    }
    const buf = fs.readFileSync(fullPath);
    const h = crypto.createHash('sha256').update(buf).digest('hex');
    if (h !== clip.sha256) {
      console.error(`FATAL: Frozen baseline clip modified: ${clip.path}`);
      process.exit(1);
    }
  }
  console.log('Frozen baseline clips verified intact (45 baseline clips untouched).\n');

  // Load existing manifest
  let manifest = { generatedAt: new Date().toISOString(), clips: {} };
  if (fs.existsSync(MANIFEST_PATH)) {
    manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  }

  const langsToProcess = targetLangs || ALL_LANGS;
  console.log(`Target languages for generation: ${langsToProcess.join(', ')}`);

  // Calculate totals and cost estimate
  let totalCharacters = 0;
  let itemsToGenerate = [];

  for (const [clipId, langMap] of Object.entries(STATIC_PROMPTS)) {
    for (const lang of langsToProcess) {
      const text = langMap[lang];
      if (!text) continue;

      // Skip if clip is frozen baseline
      const isFrozen = ['en', 'hi', 'ta', 'mr', 'ur'].includes(lang) &&
        ['scheme_msy', 'scheme_mcf', 'scheme_tls', 'portal_welcome', 'apply_modal_warning', 'doc_guidance_intro', 'roadmap_intro', 'apply_route_notice', 'docs_checklist'].includes(clipId);
      if (isFrozen) {
        continue;
      }

      // Check if already in manifest with valid file
      const existing = manifest.clips?.[clipId]?.[lang];
      if (existing && existing.path) {
        const full = path.resolve(__dirname, '../frontend/public' + existing.path);
        if (fs.existsSync(full) && fs.statSync(full).size >= 2048) {
          continue; // Already generated
        }
      }

      totalCharacters += text.length;
      itemsToGenerate.push({ clipId, lang, text });
    }
  }

  // Cost estimate: ₹0.00015 per character (~$0.0018 / 1K chars)
  const estInr = (totalCharacters * 0.00015).toFixed(2);
  const estUsd = (totalCharacters * 0.0000018).toFixed(4);

  console.log(`\n--- Character & Cost Budget Pre-Check ---`);
  console.log(`Clips to generate: ${itemsToGenerate.length}`);
  console.log(`Total characters:  ${totalCharacters}`);
  console.log(`Estimated cost:    ₹${estInr} (~$${estUsd} USD)`);
  console.log(`Primary Engine:    Sarvam Bulbul v3 (speaker: shubh)`);
  console.log(`----------------------------------------\n`);

  if (isDryRun) {
    console.log('DRY RUN MODE: Skipping API synthesis. All checks completed successfully.');
    process.exit(0);
  }

  if (itemsToGenerate.length === 0) {
    console.log('All static clips already generated and verified on disk! Manifest is up to date.');
    process.exit(0);
  }

  if (!SARVAM_KEY) {
    console.error('FATAL: SARVAM_API_KEY environment variable is required to generate new clips.');
    process.exit(1);
  }

  let generatedCount = 0;
  let failCount = 0;

  for (let i = 0; i < itemsToGenerate.length; i++) {
    const item = itemsToGenerate[i];
    const targetSarvamLang = SARVAM_LANG_MAP[item.lang];
    if (!targetSarvamLang) {
      console.warn(`Skipping unsupported Sarvam language: ${item.lang}`);
      continue;
    }

    process.stdout.write(`[${i + 1}/${itemsToGenerate.length}] Generating [${item.lang}] ${item.clipId}... `);

    try {
      const audioBuf = await synthesizeSarvam(item.text, targetSarvamLang);
      if (!isValidMp3(audioBuf)) {
        throw new Error(`Audio response is under 2048 bytes or lacks valid MP3 header (${audioBuf.length} bytes)`);
      }

      // Hash content
      const fullHash = crypto.createHash('sha256').update(audioBuf).digest('hex');
      const hash8 = fullHash.slice(0, 8);
      const textHash = crypto.createHash('sha256').update(item.text).digest('hex');

      // Filename
      const fileName = `${item.clipId}.${hash8}.mp3`;
      const langDir = path.join(OUTPUT_DIR, item.lang);
      if (!fs.existsSync(langDir)) {
        fs.mkdirSync(langDir, { recursive: true });
      }
      const filePath = path.join(langDir, fileName);
      fs.writeFileSync(filePath, audioBuf);

      // Update manifest
      if (!manifest.clips[item.clipId]) {
        manifest.clips[item.clipId] = {};
      }
      manifest.clips[item.clipId][item.lang] = {
        clipId: item.clipId,
        language: item.lang,
        path: `/audio/${item.lang}/${fileName}`,
        sizeBytes: audioBuf.length,
        sha256: fullHash,
        textHash: textHash,
        modelId: 'bulbul:v3',
        voiceId: 'shubh',
        generatedAt: new Date().toISOString(),
        text: item.text
      };

      console.log(`OK (${audioBuf.length} bytes, ${fileName})`);
      generatedCount++;

      // Rate limit backoff: 300ms
      await sleep(300);
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
      failCount++;
      // Exit code 1 on any API error per requirement
      console.error(`FATAL: Static voice generation failed on [${item.lang}] ${item.clipId}: ${err.message}`);
      process.exit(1);
    }
  }

  // Save updated manifest
  manifest.updatedAt = new Date().toISOString();
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2), 'utf8');
  console.log(`\nUpdated manifest at ${MANIFEST_PATH} with ${generatedCount} new clips.`);
  console.log(`\n===============================================================`);
  console.log(`       Static Voice Generation Finished: 0 Errors              `);
  console.log(`===============================================================\n`);
}

run().catch(err => {
  console.error('Unhandled fatal error in generator:', err);
  process.exit(1);
});

